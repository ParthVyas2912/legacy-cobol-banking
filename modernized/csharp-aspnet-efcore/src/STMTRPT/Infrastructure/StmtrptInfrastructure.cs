using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.EntityFrameworkCore;
using STMTRPT.Application.Interfaces;
using STMTRPT.Domain;

namespace STMTRPT.Infrastructure
{
    public class StmtrptDbContext : DbContext
    {
        public DbSet<Stmtout> Stmtouts { get; set; }

        public StmtrptDbContext(DbContextOptions<StmtrptDbContext> options) : base(options)
        {
        }

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<Stmtout>(entity =>
            {
                entity.ToTable("stmtout", "public");

                entity.Property(e => e.StmtAcctNum)
                    .HasColumnName("stmt_acct_num")
                    .HasMaxLength(10) // COBOL: STMT-ACCT-NUM PIC 9(10)
                    .IsRequired();

                entity.Property(e => e.StmtDescription)
                    .HasColumnName("stmt_description")
                    .HasMaxLength(40) // COBOL: STMT-DESCRIPTION PIC X(40)
                    .IsRequired();

                entity.Property(e => e.StmtAmount)
                    .HasColumnName("stmt_amount")
                    .HasColumnType("NUMERIC(13, 2)") // COBOL: STMT-AMOUNT PIC -Z(11)9.99
                    .IsRequired();

                entity.Property(e => e.StmtBalance)
                    .HasColumnName("stmt_balance")
                    .HasColumnType("NUMERIC(15, 2)") // COBOL: STMT-BALANCE PIC -Z(13)9.99
                    .IsRequired();
            });
        }
    }

    public class Stmtout
    {
        [Required]
        [MaxLength(10)]
        public string StmtAcctNum { get; set; } // COBOL: STMT-ACCT-NUM PIC 9(10)

        [Required]
        [MaxLength(40)]
        public string StmtDescription { get; set; } // COBOL: STMT-DESCRIPTION PIC X(40)

        [Required]
        [Precision(13, 2)]
        public decimal StmtAmount { get; set; } // COBOL: STMT-AMOUNT PIC -Z(11)9.99

        [Required]
        [Precision(15, 2)]
        public decimal StmtBalance { get; set; } // COBOL: STMT-BALANCE PIC -Z(13)9.99
    }

    public class AccountSummaryRepository : IAccountSummaryRepository
    {
        private readonly StmtrptDbContext _context;

        public AccountSummaryRepository(StmtrptDbContext context)
        {
            _context = context ?? throw new ArgumentNullException(nameof(context));
        }

        public IEnumerable<StmtrptDomainModels.AccountSummary> ReadAccountSummaries()
        {
            return _context.Stmtouts.Select(stmt => new StmtrptDomainModels.AccountSummary
            {
                AccountNumber = stmt.StmtAcctNum,
                Balance = stmt.StmtBalance,
                AvailableCredit = stmt.StmtAmount,
                AccountStatus = StmtrptDomainModels.AccountStatusEnum.Active, // Defaulting to Active
                LastTransactionDate = DateTime.Now, // Placeholder for actual date
                Transactions = Array.Empty<StmtrptDomainModels.Transaction>() // Placeholder for transactions
            }).ToList();
        }

        public void WriteAccountSummaries(IEnumerable<StmtrptDomainModels.AccountSummary> accountSummaries)
        {
            if (accountSummaries == null) throw new ArgumentNullException(nameof(accountSummaries));

            foreach (var summary in accountSummaries)
            {
                var stmtout = new Stmtout
                {
                    StmtAcctNum = summary.AccountNumber,
                    StmtBalance = summary.Balance,
                    StmtAmount = summary.AvailableCredit,
                    StmtDescription = "Generated by STMTRPT" // Placeholder for actual description
                };

                _context.Stmtouts.Add(stmtout);
            }

            _context.SaveChanges();
        }
    }

